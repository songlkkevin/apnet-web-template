#!/usr/bin/env python3
"""Render top-level PHP pages and copy public assets into a checked static site."""

import argparse
import os
from pathlib import Path
import shutil
import subprocess
import sys
import tempfile

from check_site import check_site


ROOT = Path(__file__).resolve().parents[1]
MARKER = ".apnet-build"
MARKER_CONTENT = "Generated by APNet scripts/build_site.py\n"
PHP_RUNNER = '''
$_SERVER['PHP_SELF'] = '/' . $argv[1];
$_SERVER['SCRIPT_NAME'] = '/' . $argv[1];
$_SERVER['SCRIPT_FILENAME'] = $argv[2];
$_SERVER['DOCUMENT_ROOT'] = getcwd();
$_SERVER['HTTP_HOST'] = 'localhost';
$_SERVER['REQUEST_URI'] = '/' . $argv[1];
require $argv[1];
'''


def build_site(source, output):
    source = source.resolve()
    if output.is_symlink():
        raise ValueError("Output must not be a symbolic link")
    output = output.resolve()
    if source == output or source in output.parents or output in source.parents:
        raise ValueError("Source and output directories must not overlap")
    if not (source / "index.php").is_file():
        raise ValueError("Source must contain index.php: " + str(source))
    if output.exists():
        if not output.is_dir():
            raise ValueError("Output is not a directory: " + str(output))
        marker = output / MARKER
        if any(output.iterdir()) and (not marker.is_file() or
                                     marker.read_text() != MARKER_CONTENT):
            raise ValueError("Output is not a generated APNet directory; choose an empty output: " + str(output))
    php = shutil.which("php")
    if not php:
        raise ValueError("PHP CLI is required; install PHP and ensure php is on PATH")
    output.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix=".apnet-build-", dir=output.parent) as temporary:
        staging = Path(temporary) / "site"
        staging.mkdir()
        pages = sorted(source.glob("*.php"))
        for page in pages:
            result = subprocess.run(
                [php, "-d", "display_errors=stderr", "-d", "log_errors=0",
                 "-d", "error_reporting=-1", "-r", PHP_RUNNER, page.name, str(page)],
                cwd=source, env=dict(os.environ, APNET_STATIC="1"),
                capture_output=True, text=True, encoding="utf-8", timeout=30)
            if result.returncode or result.stderr:
                raise ValueError("Failed to render {}:\n{}".format(
                    page.name, result.stderr or "PHP exited with status " + str(result.returncode)))
            (staging / page.with_suffix(".html").name).write_text(result.stdout, encoding="utf-8")
        for directory in ("css", "js", "images", "files"):
            assets = source / directory
            if assets.is_symlink():
                raise ValueError("Public asset directories must not be symbolic links: " + directory)
            for asset in sorted(assets.rglob("*")) if assets.exists() else []:
                relative = asset.relative_to(source)
                if any(part.startswith(".") for part in relative.parts) or asset.suffix.lower() == ".php":
                    continue
                if asset.is_symlink():
                    raise ValueError("Public assets must not be symbolic links: " + str(relative))
                if asset.is_file():
                    target = staging / relative
                    target.parent.mkdir(parents=True, exist_ok=True)
                    shutil.copyfile(asset, target)
        robots = source / "robots.txt"
        if robots.is_file():
            shutil.copyfile(robots, staging / "robots.txt")
        cname = source.parent / "CNAME"
        if cname.is_file():
            shutil.copyfile(cname, staging / "CNAME")
        (staging / ".nojekyll").touch()
        (staging / MARKER).write_text(MARKER_CONTENT, encoding="utf-8")
        errors = check_site(staging)
        if errors:
            raise ValueError("Static site validation failed:\n- " + "\n- ".join(errors))
        if output.exists():
            shutil.rmtree(output)
        staging.replace(output)
    return len(pages)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, default=ROOT / "web")
    parser.add_argument("--output", type=Path, default=ROOT / "static_site")
    args = parser.parse_args()
    try:
        count = build_site(args.source, args.output)
    except (OSError, ValueError, subprocess.TimeoutExpired) as error:
        print("Build failed: " + str(error), file=sys.stderr)
        return 1
    print("Built and validated {} pages in {}".format(count, args.output.resolve()))
    return 0


if __name__ == "__main__":
    sys.exit(main())
